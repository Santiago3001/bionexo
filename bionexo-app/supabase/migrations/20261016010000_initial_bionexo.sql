create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text not null,
  company_name text not null,
  cuit text not null default '',
  city text not null,
  business_type text not null default '',
  role text not null check (role in ('comprador', 'vendedor', 'transportista')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.offers (
  id bigint generated by default as identity primary key,
  owner_id uuid references public.profiles(id) on delete cascade,
  seller_name text not null,
  product text not null,
  category text not null default 'Subproducto agroindustrial',
  origin_process text not null default '',
  quantity_tons numeric(12,2) not null check (quantity_tons > 0),
  frequency text not null default 'Mensual',
  availability_months integer not null default 1 check (availability_months > 0),
  city text not null,
  presentation text not null default '',
  quality_notes text not null default '',
  price_per_ton numeric(12,2) not null check (price_per_ton >= 0),
  min_lot_tons numeric(12,2) not null default 1 check (min_lot_tons > 0),
  pickup_terms text not null default '',
  loading_method text not null default '',
  storage_restrictions text not null default '',
  documents_notes text not null default '',
  quality_score smallint not null default 7 check (quality_score between 1 and 10),
  status text not null default 'active' check (status in ('draft', 'active', 'paused', 'closed')),
  is_simulated boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.purchase_needs (
  id bigint generated by default as identity primary key,
  buyer_id uuid not null references public.profiles(id) on delete cascade,
  product text not null,
  quantity_tons numeric(12,2) not null check (quantity_tons > 0),
  frequency text not null default 'Mensual',
  duration_months integer not null default 12 check (duration_months > 0),
  delivery_city text not null,
  max_radius_km integer not null default 150 check (max_radius_km > 0),
  max_price_per_ton numeric(12,2),
  quality_requirements text not null default '',
  accepted_presentation text not null default '',
  required_from date,
  delivery_terms text not null default '',
  required_documents text not null default '',
  status text not null default 'active' check (status in ('draft', 'active', 'paused', 'closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.transport_routes (
  id bigint generated by default as identity primary key,
  carrier_id uuid not null references public.profiles(id) on delete cascade,
  vehicle_type text not null,
  capacity_tons numeric(12,2) not null check (capacity_tons > 0),
  origin_city text not null,
  destination_city text not null,
  available_date date not null,
  route_type text not null check (route_type in ('planificada', 'retorno')),
  price_per_km numeric(12,2),
  status text not null default 'available' check (status in ('available', 'reserved', 'completed', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id text primary key,
  created_by uuid not null references public.profiles(id) on delete cascade,
  kind text not null check (kind in ('compra', 'venta', 'trueque')),
  product text not null,
  quantity_tons numeric(12,2) not null,
  origin_city text not null,
  destination_city text not null,
  buyer_name text not null,
  seller_name text not null,
  carrier_name text not null default '',
  status_step smallint not null default 0 check (status_step between 0 and 4),
  eta text not null default '',
  value_usd numeric(12,2) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at before update on public.profiles
for each row execute function public.set_updated_at();

drop trigger if exists offers_set_updated_at on public.offers;
create trigger offers_set_updated_at before update on public.offers
for each row execute function public.set_updated_at();

drop trigger if exists needs_set_updated_at on public.purchase_needs;
create trigger needs_set_updated_at before update on public.purchase_needs
for each row execute function public.set_updated_at();

drop trigger if exists routes_set_updated_at on public.transport_routes;
create trigger routes_set_updated_at before update on public.transport_routes
for each row execute function public.set_updated_at();

drop trigger if exists orders_set_updated_at on public.orders;
create trigger orders_set_updated_at before update on public.orders
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (
    id, email, full_name, company_name, cuit, city, business_type, role
  ) values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'company_name', ''),
    coalesce(new.raw_user_meta_data ->> 'cuit', ''),
    coalesce(new.raw_user_meta_data ->> 'city', ''),
    coalesce(new.raw_user_meta_data ->> 'business_type', ''),
    case
      when new.raw_user_meta_data ->> 'role' in ('comprador', 'vendedor', 'transportista')
        then new.raw_user_meta_data ->> 'role'
      else 'comprador'
    end
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.current_user_has_role(expected_role text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = expected_role
  );
$$;

