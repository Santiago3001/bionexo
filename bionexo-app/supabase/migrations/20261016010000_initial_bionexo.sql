drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles for select to authenticated
using (id = auth.uid());
drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles for update to authenticated
using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "offers_read_active" on public.offers;
create policy "offers_read_active" on public.offers for select to authenticated
using (status = 'active' or owner_id = auth.uid());
drop policy if exists "sellers_insert_offers" on public.offers;
create policy "sellers_insert_offers" on public.offers for insert to authenticated
with check (owner_id = auth.uid() and public.current_user_has_role('vendedor'));
drop policy if exists "sellers_update_own_offers" on public.offers;
create policy "sellers_update_own_offers" on public.offers for update to authenticated
using (owner_id = auth.uid()) with check (owner_id = auth.uid());
drop policy if exists "sellers_delete_own_offers" on public.offers;
create policy "sellers_delete_own_offers" on public.offers for delete to authenticated
using (owner_id = auth.uid());

drop policy if exists "buyers_manage_own_needs" on public.purchase_needs;
create policy "buyers_manage_own_needs" on public.purchase_needs for all to authenticated
using (buyer_id = auth.uid())
with check (buyer_id = auth.uid() and public.current_user_has_role('comprador'));

drop policy if exists "routes_read_authenticated" on public.transport_routes;
create policy "routes_read_authenticated" on public.transport_routes for select to authenticated
using (true);
drop policy if exists "carriers_insert_routes" on public.transport_routes;
create policy "carriers_insert_routes" on public.transport_routes for insert to authenticated
with check (carrier_id = auth.uid() and public.current_user_has_role('transportista'));
drop policy if exists "carriers_update_own_routes" on public.transport_routes;
create policy "carriers_update_own_routes" on public.transport_routes for update to authenticated
using (carrier_id = auth.uid()) with check (carrier_id = auth.uid());
drop policy if exists "carriers_delete_own_routes" on public.transport_routes;
create policy "carriers_delete_own_routes" on public.transport_routes for delete to authenticated
using (carrier_id = auth.uid());

drop policy if exists "orders_manage_own" on public.orders;
create policy "orders_manage_own" on public.orders for all to authenticated
using (created_by = auth.uid()) with check (created_by = auth.uid());

